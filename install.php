<?php if ($done): ?>
  <div class="ok">Installation complete. Your store is ready.</div>
  <p><strong>Important:</strong> delete <code>install.php</code> from the server now.</p>
  <a class="btn" href="index.php">Open the store</a> &nbsp; <a class="btn" href="admin/login.php">Open admin panel</a>
<?php elseif ($installed): ?>
  <p>This store is already installed. To reinstall, delete <code>config/config.php</code> first.</p>
  <a class="btn" href="index.php">Open the store</a>
<?php else: ?>
  <p>Enter your MySQL details and choose the admin login. This creates the tables and starter content.</p>
  <?php foreach ($errors as $er): ?><div class="err"><?= $h($er) ?></div><?php endforeach; ?>
  <form method="post" autocomplete="off">
    <h2>Database</h2>
    <div class="grid">
      <div><label>Host</label><input name="db_host" value="<?= $h($f['db_host']) ?>" required></div>
      <div><label>Port</label><input name="db_port" value="<?= $h($f['db_port']) ?>" required></div>
    </div>
    <label>Database name</label><input name="db_name" value="<?= $h($f['db_name']) ?>" required>
    <div class="grid">
      <div><label>Username</label><input name="db_user" value="<?= $h($f['db_user']) ?>" required></div>
      <div><label>Password</label><input type="password" name="db_pass" value=""></div>
    </div>
    <h2>Admin account</h2>
    <label>Your name</label><input name="admin_name" value="<?= $h($f['admin_name']) ?>" required>
    <label>Admin email</label><input type="email" name="admin_email" value="<?= $h($f['admin_email']) ?>" required>
    <label>Admin password (min 8 characters)</label><input type="password" name="admin_pass" minlength="8" required>
    <button type="submit">Install store</button>
  </form>
<?php endif; ?>
