<?php
// One-time installer: creates the tables, starter data, admin login and config/config.php.
$root = __DIR__;
$configFile = $root . '/config/config.php';
$installed = is_file($configFile);
$errors = [];
$done = false;
$f = ['db_host' => 'localhost', 'db_port' => '3306', 'db_name' => 'holistic_store', 'db_user' => 'root', 'db_pass' => '', 'admin_name' => '', 'admin_email' => ''];

if (!$installed && $_SERVER['REQUEST_METHOD'] === 'POST') {
    foreach ($f as $k => $v) {
        $f[$k] = trim((string) ($_POST[$k] ?? ''));
    }
    $adminPass = (string) ($_POST['admin_pass'] ?? '');
    if (!preg_match('/^[A-Za-z0-9_]+$/', $f['db_name'])) {
        $errors[] = 'Database name may contain only letters, numbers and underscores.';
    }
    if ($f['admin_name'] === '' || !filter_var($f['admin_email'], FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'Enter the admin name and a valid admin email.';
    }
    if (strlen($adminPass) < 8) {
        $errors[] = 'Admin password must be at least 8 characters.';
    }
    if (!is_writable($root . '/config')) {
        $errors[] = 'The config/ folder is not writable.';
    }

    if (!$errors) {
        try {
            $opt = [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION];
            $dsn = 'mysql:host=' . $f['db_host'] . ';port=' . (int) $f['db_port'] . ';charset=utf8mb4';
            try {
                // Works on local servers; on shared hosting the database usually already exists.
                $pdo = new PDO($dsn, $f['db_user'], $f['db_pass'], $opt);
                $pdo->exec('CREATE DATABASE IF NOT EXISTS `' . $f['db_name'] . '` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci');
            } catch (PDOException $ignored) {
            }
            $pdo = new PDO($dsn . ';dbname=' . $f['db_name'], $f['db_user'], $f['db_pass'], $opt);

            foreach (explode(";\n", str_replace("\r\n", "\n", file_get_contents($root . '/database/schema.sql'))) as $sql) {
                $sql = trim(preg_replace('/^--.*$/m', '', $sql));
                if ($sql !== '') {
                    $pdo->exec($sql);
                }
            }
            require $root . '/database/seed.php';
            seed_database($pdo);

            $st = $pdo->prepare('INSERT INTO admins (name, email, password_hash) VALUES (?, ?, ?) ON DUPLICATE KEY UPDATE password_hash = VALUES(password_hash), name = VALUES(name)');
            $st->execute([$f['admin_name'], strtolower($f['admin_email']), password_hash($adminPass, PASSWORD_DEFAULT)]);

            $config = "<?php\n// Generated by install.php\n"
                . "define('DB_HOST', " . var_export($f['db_host'], true) . ");\n"
                . "define('DB_PORT', " . (int) $f['db_port'] . ");\n"
                . "define('DB_NAME', " . var_export($f['db_name'], true) . ");\n"
                . "define('DB_USER', " . var_export($f['db_user'], true) . ");\n"
                . "define('DB_PASS', " . var_export($f['db_pass'], true) . ");\n"
                . "define('APP_DEBUG', false); // set true to show PHP errors while developing\n";
            if (file_put_contents($configFile, $config) === false) {
                throw new RuntimeException('Could not write config/config.php.');
            }
            $done = true;
        } catch (Throwable $ex) {
            $errors[] = 'Installation failed: ' . $ex->getMessage();
        }
    }
}
$h = fn($v) => htmlspecialchars((string) $v, ENT_QUOTES, 'UTF-8');
?>
